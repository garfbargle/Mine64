"""Generate Mine64's tiny, original N64-ready art set.

The project intentionally does not bundle Minecraft Classic artwork.  These
procedural 16-colour tiles and 5x7 UI glyphs are generated locally, so a clean
checkout can build without downloading proprietary game assets.
"""

from pathlib import Path

ASSET_DIR = Path("assets")


def rgba5551(rgb):
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | 1


def pack_nibbles(values):
    result = []
    for offset in range(0, len(values), 8):
        word = 0
        for value in values[offset:offset + 8]:
            word = (word << 4) | value
        result.append(word)
    return result


def tile(kind, x, y):
    if kind == "grass_top":
        return 1 + ((x * 3 + y * 5 + x * y) % 3)
    if kind == "grass_side":
        if y < 4:
            return 1 + ((x + y) % 3)
        return 4 + ((x * 5 + y * 3) % 3)
    if kind == "cobblestone":
        return 1 + (((x // 4) + (y // 3) + (x * y) // 19) % 4)
    if kind == "wood_top":
        return 1 + ((max(abs(x - 7), abs(y - 7)) + x // 5) % 4)
    if kind == "wood_side":
        return 1 + ((x // 3 + (y // 5) * 2) % 4)
    if kind == "leaves":
        return 1 + ((x * 7 + y * 11 + x * y) % 4)
    if kind == "planks":
        return 1 + ((x // 4 + (y // 5) * 2) % 4)
    if kind == "bricks":
        return 1 + (((x // 6 + (y // 4) * 3 + ((y // 4) & 1)) % 4))
    return 1 + ((x * 7 + y * 3 + (x * y) // 9) % 4)


